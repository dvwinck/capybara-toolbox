#!/usr/bin/env python3
"""Keeps the ar-board plugin consistent from one source of truth: the script's VERSION.

It propagates the version into .claude-plugin/plugin.json and keeps the second skill
(question-board) honest: its scripts/ar_board.py is a generated byte copy of the engine, so each
skill folder stays self-contained. It also generates, for each skill, a single-file variant in
dist/: a self-contained SKILL.md with the script embedded, for surfaces that accept a lone
SKILL.md (the plugin install is the supported route). In those variants the bundled-script path
is replaced by ~/.claude/ar-board/ar_board.py, where step 0 installs the script (both variants
share that one path, since it is the same script). It also reports problems it cannot fix by
itself (missing CHANGELOG entry, stale header comment, missing markers).

Usage (from the plugin directory or anywhere):
  python3 tools/sync.py           # write whatever is out of sync
  python3 tools/sync.py --check   # only verify (exit 1 if anything differs or is wrong)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = "skills/ar-board"
SCRIPT = f"{SKILL_DIR}/scripts/ar_board.py"  # the engine: the single source of truth
SKILL = f"{SKILL_DIR}/SKILL.md"
QB_DIR = "skills/question-board"
QB_SKILL = f"{QB_DIR}/SKILL.md"
QB_SCRIPT = f"{QB_DIR}/scripts/ar_board.py"  # generated: a byte copy of SCRIPT
PLUGIN = ".claude-plugin/plugin.json"
SINGLE = "dist/ar-board-single-file.SKILL.md"
QB_SINGLE = "dist/question-board-single-file.SKILL.md"
CHANGELOG = "CHANGELOG.md"

INPUTS = [SCRIPT, SKILL, QB_SKILL, PLUGIN, CHANGELOG]
GENERATED = [PLUGIN, SINGLE, QB_SINGLE, QB_SCRIPT]

BUNDLED = "${CLAUDE_SKILL_DIR}/scripts/ar_board.py"  # how the lean SKILL.md files name the script
INSTALLED = "$HOME/.claude/ar-board/ar_board.py"  # where the single-file variants install it
SINGLE_STEP0 = """### 0. Install the script (once per machine)

```bash
test -f "{installed}" && grep -q 'ar-board {version}' "{installed}" && echo OK || echo FALTA
```

`OK` means the script is installed and its version matches. `FALTA` means "missing".

If the output is `FALTA` (or the installed version is older), run `mkdir -p ~/.claude/ar-board`. Then write the content of the **Script** section at the end of this file to `~/.claude/ar-board/ar_board.py` (a literal copy, no changes). The commands below use that path. It needs only `python3` (stdlib).
"""


def locate(name):
    return rf"(?s)<!-- {re.escape(name)}:locate-script -->.*?<!-- /{re.escape(name)}:locate-script -->\n"


def read(root, rel):
    return (root / rel).read_text(encoding="utf-8")


def dump_json(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def sub_once(pattern, repl, text, what):
    """re.sub that requires exactly one match: a vanished anchor must not pass silently."""
    out, n = re.subn(pattern, repl, text)
    if n != 1:
        raise SystemExit(f"sync: anchor not found ({n} matches, expected 1): {what}")
    return out


def script_version(script):
    return re.search(r'^VERSION = "(\d+\.\d+\.\d+)"', script, re.M).group(1)


def single_file(root, skill_rel, name, script, version):
    skill = read(root, skill_rel)
    single = sub_once(locate(name), lambda m: SINGLE_STEP0.format(version=version, installed=INSTALLED), skill,
                      f"{skill_rel} locate-script markers")
    if BUNDLED not in single:
        raise SystemExit(f"sync: {skill_rel} no longer runs the script as {BUNDLED}")
    single = single.replace(BUNDLED, INSTALLED)
    return single.rstrip("\n") + "\n\n## Script\n\nWrite this content, unchanged, to `~/.claude/ar-board/ar_board.py`:\n\n```python\n" + script.rstrip("\n") + "\n```\n"


def build(root):
    """Return {relative path: expected content} for every generated file."""
    script = read(root, SCRIPT)
    version = script_version(script)

    plugin = json.loads(read(root, PLUGIN))
    plugin["version"] = version

    return {
        PLUGIN: dump_json(plugin),
        SINGLE: single_file(root, SKILL, "ar-board", script, version),
        QB_SINGLE: single_file(root, QB_SKILL, "question-board", script, version),
        QB_SCRIPT: script,
    }


def problems(root):
    """Things the tool cannot fix by itself; each one is a message."""
    out = []
    script = read(root, SCRIPT)
    version = script_version(script)
    if not re.search(rf"^# ar-board {re.escape(version)} - ", script, re.M):
        out.append(f"{SCRIPT}: header comment must say 'ar-board {version}' (VERSION is {version})")
    if not re.search(rf"^## \[{re.escape(version)}\]", read(root, CHANGELOG), re.M):
        out.append(f"{CHANGELOG}: no '## [{version}]' entry")
    return out


def main(argv, root=ROOT):
    files = build(root)
    found = problems(root)
    stale = [rel for rel, text in files.items() if not (root / rel).exists() or read(root, rel) != text]
    if "--check" in argv:
        for rel in stale:
            print(f"out of sync: {rel}")
        for msg in found:
            print(f"problem: {msg}")
        return 1 if (stale or found) else 0
    for rel in stale:
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(files[rel], encoding="utf-8")
        print(f"updated: {rel}")
    for msg in found:
        print(f"problem: {msg}")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
